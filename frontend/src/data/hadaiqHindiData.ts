/**
 * Maps a physical printed Hindi book page number (1..490) to the authentic scanned PDF page number (8..497).
 * - Front matter pages 1..7 (Cover, publisher details A-1..A-6)
 * - Printed Page 1 -> PDF Page 8 (Offset: +7)
 * - Printed Page 490 -> PDF Page 497 (Offset: +7)
 */
export function getPdfPageFromPrintedPage(printedPage: number): number {
  const clamped = Math.max(1, Math.min(HADAIQ_HINDI_PRINTED_TOTAL_PAGES, printedPage));
  return clamped + 7;
}

/**
 * Maps an authentic scanned PDF page number (1..498) to the physical printed Hindi book page number (1..490).
 */
export function getPrintedPageFromPdfPage(pdfPage: number): number {
  if (pdfPage <= 7) return 1;
  if (pdfPage <= 497) return Math.min(HADAIQ_HINDI_PRINTED_TOTAL_PAGES, pdfPage - 7);
  return HADAIQ_HINDI_PRINTED_TOTAL_PAGES;
}

export interface HadaiqHindiPageMapping {
  printedPage: number;
  pdfPage: number;
}

export const HADAIQ_HINDI_PRINTED_PAGES: HadaiqHindiPageMapping[] = Array.from(
  { length: HADAIQ_HINDI_PRINTED_TOTAL_PAGES },
  (_, i) => {
    const printedPage = i + 1;
    return {
      printedPage,
      pdfPage: getPdfPageFromPrintedPage(printedPage),
    };
  }
);

