export function getBookById(id: string): IslamicBook | undefined {
  return ISLAMIC_BOOKS.find((book) => book.id === id);
}

export function getBooksByCategory(category: LibraryCategory): IslamicBook[] {
  if (category === 'all') return ISLAMIC_BOOKS;
  return ISLAMIC_BOOKS.filter((book) => book.category === category);
}

export function getFeaturedBooks(): IslamicBook[] {
  return ISLAMIC_BOOKS.filter((book) => book.isFeatured);
}

export function searchBooks(
  query: string,
  category: LibraryCategory = 'all',
  language: string = 'all'
): IslamicBook[] {
  const q = query.trim().toLowerCase();
  return ISLAMIC_BOOKS.filter((book) => {
    // Category match
    if (category !== 'all' && book.category !== category) {
      return false;
    }
    // Language match
    if (language !== 'all' && !book.languagesAvailable.includes(language)) {
      return false;
    }
    // Query search match
    if (!q) return true;

    const matchTitle = book.title.toLowerCase().includes(q);
    const matchArabic = book.arabicTitle.includes(q);
    const matchUrdu = book.urduTitle ? book.urduTitle.includes(q) : false;
    const matchTranslit = book.transliteration ? book.transliteration.toLowerCase().includes(q) : false;
    const matchAuthor = book.author.toLowerCase().includes(q) || (book.authorArabic && book.authorArabic.includes(q));
    const matchCompiler = book.compiler ? book.compiler.toLowerCase().includes(q) : false;
    const matchDesc = book.description.toLowerCase().includes(q);
    const matchTradition = book.tradition.toLowerCase().includes(q);
    const matchTags = book.tags.some((t) => t.toLowerCase().includes(q));

    return (
      matchTitle ||
      matchArabic ||
      matchUrdu ||
      matchTranslit ||
      matchAuthor ||
      matchCompiler ||
      matchDesc ||
      matchTradition ||
      matchTags
    );
  });
}

